namespace Turian.Editor.Core;

/// <summary>Composes an exported runtime from compiler symbols rather than runtime assembly discovery.</summary>
static class ExportRuntimeGenerator
{
    const string core = "global::Turian.Engine.Core";
    static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    internal static async Task GenerateAsync(string projectPath, IBuildAppSettings settings, BuildProfile profile,
        ILogger logger)
    {
        using var workspace = MSBuildWorkspace.Create(new Dictionary<string, string>
        {
            ["TurianDefines"] = string.Join(';', profile.Symbols)
        });
        var project = await workspace.OpenProjectAsync(projectPath).ConfigureAwait(false);
        var compilation = await project.GetCompilationAsync().ConfigureAwait(false)
                          ?? throw new InvalidOperationException("Could not inspect the export compilation.");
        var graph = CsProjectGenerator.DiscoverAssemblies(settings);
        var manifest = UserCodeTypeManifestGenerator.Generate(settings.AssetsAbsoluteDir, logger,
            settings.TitleToPathFriendly, graph, profile.Target);
        await File.WriteAllTextAsync(Path.Combine(Path.GetDirectoryName(projectPath)!, "GeneratedExportRuntime.cs"),
            GenerateSource(compilation, manifest)).ConfigureAwait(false);
    }

    internal static string GenerateSource(Compilation compilation, UserCodeTypeManifest manifest)
    {
        var assemblies = RuntimeAssemblies(compilation);
        var types = assemblies.SelectMany(static assembly => Types(assembly.GlobalNamespace))
            .Where(static type => !type.IsGenericType && type.DeclaredAccessibility == Accessibility.Public).ToList();
        var ids = manifest.Types.Where(static entry => !entry.EditorOnly)
            .ToDictionary(static entry => entry.FullyQualifiedName, static entry => entry.TypeId, StringComparer.Ordinal);
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Turian;\n");
        code.AppendLine("internal static class GeneratedExportRuntime { internal static void Initialize() {");
        code.AppendLine($"{core}.GeneratedJson.Configure(static options => new ExportJsonContext(options));");
        code.AppendLine($"{core}.ExportRuntime.CreatePlayer = static () => new {core}.HeadlessPlayer();");
        var valueTypes = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        var referenceTypes = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in types.OrderBy(static type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            EmitTypeIds(code, type, ids);
            EmitConstructor(code, type, valueTypes, referenceTypes);
        }

        EmitReferences(code, referenceTypes);
        EmitModules(code, assemblies, types);
        EmitValueContext(code, valueTypes);
        return code.ToString();
    }

    static IReadOnlyList<IAssemblySymbol> RuntimeAssemblies(Compilation compilation)
    {
        var engine = compilation.GetTypeByMetadataName("Turian.Engine.Core.IdObject")?.ContainingAssembly
                     ?? throw new InvalidOperationException("The export has no engine runtime reference.");
        return [.. compilation.SourceModule.ReferencedAssemblySymbols.Append(compilation.Assembly)
            .Where(assembly => SymbolEqualityComparer.Default.Equals(assembly, engine)
                               || assembly.Modules.Any(module => module.ReferencedAssemblySymbols.Any(reference =>
                                   SymbolEqualityComparer.Default.Equals(reference, engine))))];
    }

    static void EmitTypeIds(StringBuilder code, INamedTypeSymbol type, IReadOnlyDictionary<string, Guid> ids)
    {
        var name = type.ToDisplayString(TypeFormat);
        var attribute = type.GetAttributes().FirstOrDefault(static attribute =>
            attribute.AttributeClass?.ToDisplayString() == "MASS4.Attributes.TypeIdAttribute");
        if (Guid.TryParse(attribute?.ConstructorArguments.FirstOrDefault().Value as string, out var id))
        {
            code.AppendLine($"{core}.TypeRegistry.Register(new global::System.Guid(\"{id}\"), typeof({name}));");
        }

        if (ids.TryGetValue(type.ToDisplayString(), out var manifestId))
        {
            code.AppendLine($"{core}.TypeRegistry.Register(new global::System.Guid(\"{manifestId}\"), typeof({name}));");
        }
    }

    static void EmitConstructor(StringBuilder code, INamedTypeSymbol type, HashSet<ITypeSymbol> values,
        HashSet<ITypeSymbol> references)
    {
        if (!DerivesFrom(type, "Turian.Engine.Core.IdObject") || type.IsAbstract)
        {
            return;
        }

        if (type.InstanceConstructors.Any(static constructor => constructor.DeclaredAccessibility == Accessibility.Public
                                                               && constructor.Parameters.Length == 0))
        {
            code.AppendLine($"{core}.GeneratedObjectFactory.Register<{type.ToDisplayString(TypeFormat)}>();");
        }

        foreach (var memberType in Members(type)) { AddValue(memberType, values, references); }
    }

    static void EmitReferences(StringBuilder code, HashSet<ITypeSymbol> referenceTypes)
    {
        foreach (var reference in referenceTypes.OrderBy(static type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            var ancestor = ReferenceAncestor(reference)!;
            var name = reference.ToDisplayString(TypeFormat);
            code.AppendLine($"{core}.AssetReferenceJsonConverterFactory.Register<{name}, {ancestor.TypeArguments[0].ToDisplayString(TypeFormat)}>(static id => new {name}(id));");
        }
    }

    static void EmitModules(StringBuilder code, IReadOnlyList<IAssemblySymbol> assemblies,
        IReadOnlyList<INamedTypeSymbol> types)
    {
        code.AppendLine($"{core}.ExportRuntime.ConfigureServices = static services => {{");
        foreach (var assembly in ModuleOrder(assemblies))
        {
            foreach (var type in types.Where(type => SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, assembly)
                                                    && !type.IsAbstract && type.AllInterfaces.Any(static contract =>
                                                        contract.ToDisplayString() == "Turian.Engine.Core.IEngineServiceModule"))
                         .OrderBy(static type => type.ToDisplayString(), StringComparer.Ordinal))
            {
                code.AppendLine($"new {type.ToDisplayString(TypeFormat)}().ConfigureServices(services);");
            }
        }

        code.AppendLine("};\n}\n}");
    }

    static void EmitValueContext(StringBuilder code, HashSet<ITypeSymbol> valueTypes)
    {
        code.AppendLine("[global::System.Text.Json.Serialization.JsonSourceGenerationOptions(IncludeFields = true, IgnoreReadOnlyProperties = true, WriteIndented = true)]");
        foreach (var value in valueTypes.OrderBy(static type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            code.AppendLine($"[global::System.Text.Json.Serialization.JsonSerializable(typeof({value.ToDisplayString(TypeFormat)}))]");
        }

        code.AppendLine("internal partial class ExportJsonContext : global::System.Text.Json.Serialization.JsonSerializerContext;");
    }

    static void AddValue(ITypeSymbol type, HashSet<ITypeSymbol> values, HashSet<ITypeSymbol> references)
    {
        AddChildTypes(type, values, references);
        if (IsObjectList(type)) { return; }
        if (ReferenceAncestor(type) is not null)
        {
            references.Add(type);
            return;
        }

        if (!IsValueContract(type) || !values.Add(type.WithNullableAnnotation(NullableAnnotation.None)))
        {
            return;
        }

        AddValueMembers(type, values, references);
    }

    static bool IsObjectList(ITypeSymbol type) => type is INamedTypeSymbol named
        && named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.List<T>"
        && named.TypeArguments.Any(static argument => DerivesFrom(argument, "Turian.Engine.Core.IdObject"));

    static bool IsValueContract(ITypeSymbol type) => !DerivesFrom(type, "Turian.Engine.Core.IdObject")
        && type.ToDisplayString() is not ("Turian.Engine.Core.NodeCollection" or "Turian.Engine.Core.ComponentCollection");

    static void AddChildTypes(ITypeSymbol type, HashSet<ITypeSymbol> values, HashSet<ITypeSymbol> references)
    {
        if (type is IArrayTypeSymbol array)
        {
            AddValue(array.ElementType, values, references);
        }

        if (type is INamedTypeSymbol named)
        {
            foreach (var argument in named.TypeArguments) { AddValue(argument, values, references); }
        }
    }

    static void AddValueMembers(ITypeSymbol type, HashSet<ITypeSymbol> values, HashSet<ITypeSymbol> references)
    {
        if (type is INamedTypeSymbol { ContainingAssembly.Name: "Turian.Engine.Core" } value)
        {
            foreach (var memberType in Members(value)) { AddValue(memberType, values, references); }
        }
    }

    static IEnumerable<ITypeSymbol> Members(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var member in current.GetMembers().Where(IsSerializableMember))
            {
                if (MemberType(member) is { } memberType)
                {
                    yield return memberType;
                }
            }
        }
    }

    static bool IsSerializableMember(ISymbol member) => !member.IsStatic
        && member.DeclaredAccessibility == Accessibility.Public && !IsIgnored(member);

    static ITypeSymbol? MemberType(ISymbol member) => member switch
    {
        IPropertySymbol { IsIndexer: false, GetMethod: not null, SetMethod: not null } property => property.Type,
        IFieldSymbol { IsReadOnly: false, IsConst: false } field => field.Type,
        _ => null,
    };

    static bool IsIgnored(ISymbol member)
    {
        var attribute = member.GetAttributes().FirstOrDefault(static attribute =>
            attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonIgnoreAttribute");
        return attribute is not null
               && (attribute.NamedArguments.FirstOrDefault(static argument => argument.Key == "Condition")
                   .Value.Value as int? ?? 1) == 1;
    }

    static INamedTypeSymbol? ReferenceAncestor(ITypeSymbol type)
    {
        for (var current = type as INamedTypeSymbol; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() == "Turian.Engine.Core.AssetReference<TAsset>")
            {
                return current;
            }
        }

        return null;
    }

    static bool DerivesFrom(ITypeSymbol type, string name)
    {
        for (var current = type as INamedTypeSymbol; current is not null; current = current.BaseType)
        {
            if (current.WithNullableAnnotation(NullableAnnotation.None).ToDisplayString() == name) { return true; }
        }

        return false;
    }

    static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol space) =>
        space.GetTypeMembers().Concat(space.GetNamespaceMembers().SelectMany(Types));

    static IEnumerable<IAssemblySymbol> ModuleOrder(IReadOnlyList<IAssemblySymbol> assemblies)
    {
        var ordered = new List<IAssemblySymbol>();
        var visited = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        foreach (var assembly in assemblies) { Visit(assembly); }
        return ordered;

        void Visit(IAssemblySymbol assembly)
        {
            if (!visited.Add(assembly)) { return; }
            foreach (var reference in assembly.Modules.SelectMany(static module => module.ReferencedAssemblySymbols)
                         .Where(reference => assemblies.Contains(reference, SymbolEqualityComparer.Default)))
            {
                Visit(reference);
            }

            ordered.Add(assembly);
        }
    }
}
