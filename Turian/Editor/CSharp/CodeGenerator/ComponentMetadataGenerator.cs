namespace Turian.CSharp.CodeGenerator;

/// <summary>Emits closed lifecycle and service-injection metadata for scene objects.</summary>
[Generator]
public sealed class ComponentMetadataGenerator : IIncrementalGenerator
{
    const string component = "Turian.Engine.Core.Component";
    const string node = "Turian.Engine.Core.Node";
    const string core = "global::Turian.Engine.Core";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (syntax, token) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token) as INamedTypeSymbol)
            .Where(static type => type is not null && (DerivesFrom(type, component) || DerivesFrom(type, node)))
            .Select(static (type, _) => Describe(type!))
            .Where(static model => model is not null);
        context.RegisterSourceOutput(types, static (output, model) =>
            output.AddSource(model!.Hint + ".ComponentMetadata.g.cs", SourceText.From(model.Source, Encoding.UTF8)));
    }

    static bool DerivesFrom(INamedTypeSymbol type, string baseType)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == baseType) { return true; }
        }

        return false;
    }

    static Model? Describe(INamedTypeSymbol type)
    {
        if (type.IsGenericType || type.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
        {
            return null;
        }

        var injections = type.GetMembers().OfType<IPropertySymbol>().Select(static property =>
                (Property: property, Attribute: Attribute(property, "Turian.Engine.Core.InjectServiceAttribute")))
            .Where(static item => item.Attribute is not null).ToList();
        var partial = type.DeclaringSyntaxReferences.Select(static reference => reference.GetSyntax())
            .OfType<ClassDeclarationSyntax>().Any(static declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
        var requiresPartial = injections.Any(static item => item.Property.SetMethod?.DeclaredAccessibility
            is not (Accessibility.Public or Accessibility.Internal));
        if ((requiresPartial && !partial) || type.ContainingType is not null)
        {
            return null;
        }

        var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var isComponent = DerivesFrom(type, component);
        var baseName = isComponent ? component : node;
        var registry = isComponent ? "GeneratedComponentMetadata" : "GeneratedNodeMetadata";
        var hint = type.ToDisplayString().Replace('.', '_');
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (requiresPartial)
        {
            if (!type.ContainingNamespace.IsGlobalNamespace)
            {
                code.AppendLine($"namespace {type.ContainingNamespace.ToDisplayString()};");
            }

            code.AppendLine($"partial class {type.Name} {{");
        }
        else
        {
            code.AppendLine($"internal static class __ComponentMetadata_{hint} {{");
        }

        code.AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        code.AppendLine("internal static void __RegisterComponentMetadata() {");
        var required = Attributes(type, "Turian.RequireComponentAttribute").Select(static attribute =>
            $"typeof({((ITypeSymbol)attribute.ConstructorArguments[0].Value!).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})");
        var allowsMultiple = !Attributes(type, "Turian.DisallowMultipleComponentAttribute").Any();
        code.AppendLine($"{core}.{registry}.Register<{fullName}>(new(");
        var callbacks = $"{Flag(type, "OnUpdate", baseName)}, {Flag(type, "OnLateUpdate", baseName)}, {Flag(type, "OnFixedUpdate", baseName)}";
        code.AppendLine(isComponent ? $"{callbacks}, {Literal(allowsMultiple)}, [{string.Join(", ", required)}],"
            : $"{callbacks.Replace(", ", " || ")},");
        code.AppendLine("static (component, services, allowMissing) => {");
        if (type.BaseType is { } parent && DerivesFrom(parent, baseName))
        {
            code.AppendLine($"{core}.{registry}.InjectBase<{parent.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>(component, services, allowMissing);");
        }

        if (injections.Count > 0) { code.AppendLine($"var value = ({fullName})component;"); }
        foreach (var (property, attribute) in injections)
        {
            if (property.SetMethod is null || property.IsIndexer
                || Attribute(property, "System.Text.Json.Serialization.JsonIgnoreAttribute") is null)
            {
                code.AppendLine("throw new global::System.InvalidOperationException(\"Injected properties require a setter and JsonIgnore.\");");
                break;
            }

            var optional = attribute!.NamedArguments.Any(static argument => argument.Key == "Optional" && argument.Value.Value is true);
            code.AppendLine($"value.@{property.Name} = {core}.GeneratedComponentMetadata.ResolveService<{property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>(services, {Literal(optional)}, allowMissing)!;");
        }

        code.AppendLine("}));\n}\n}");
        return new Model(hint, code.ToString());
    }

    static AttributeData? Attribute(ISymbol symbol, string name) =>
        symbol.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == name);

    static IEnumerable<AttributeData> Attributes(INamedTypeSymbol type, string name)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var attribute in current.GetAttributes().Where(attribute => attribute.AttributeClass?.ToDisplayString() == name))
            {
                yield return attribute;
            }
        }
    }

    static string Flag(INamedTypeSymbol type, string name, string baseName)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.GetMembers(name).OfType<IMethodSymbol>().Any(static method => method.Parameters.Length == 1
                    && method.Parameters[0].Type.SpecialType == SpecialType.System_Single))
            {
                return Literal(current.ToDisplayString() != baseName);
            }
        }

        return "false";
    }

    static string Literal(bool value) => value ? "true" : "false";

    sealed record Model(string Hint, string Source);
}
