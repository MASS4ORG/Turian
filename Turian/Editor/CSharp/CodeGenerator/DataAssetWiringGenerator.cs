namespace Turian.CSharp.CodeGenerator;

/// <summary>Emits typed method-group subscriptions with component-owned disposal and compile-time wire validation.</summary>
[Generator]
public sealed class DataAssetWiringGenerator : IIncrementalGenerator
{
    static readonly DiagnosticDescriptor InvalidWire = new("TURDDD001", "Invalid DataAsset wiring",
        "{0}", "DataAssetDrivenDesign", DiagnosticSeverity.Error, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.ForAttributeWithMetadataName("Turian.DataAssetListenAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (syntax, _) => (IMethodSymbol)syntax.TargetSymbol).Collect();
        context.RegisterSourceOutput(methods, static (output, methods) =>
        {
            foreach (var group in methods.GroupBy(static method => method.ContainingType, SymbolEqualityComparer.Default))
            {
                Emit(output, (INamedTypeSymbol)group.Key!, [.. group]);
            }
        });
    }

    static void Emit(SourceProductionContext output, INamedTypeSymbol type, IMethodSymbol[] methods)
    {
        if (type.ContainingType is not null || type.IsGenericType ||
            !type.DeclaringSyntaxReferences.All(static reference =>
                reference.GetSyntax() is ClassDeclarationSyntax syntax && syntax.Modifiers.Any(SyntaxKind.PartialKeyword)) ||
            !Inherits(type, "Turian.Engine.Core.Component"))
        {
            Error("DataAsset listeners require a top-level, non-generic partial Component.");
            return;
        }

        var subscriptions = new List<string>();
        foreach (var method in methods)
        {
            var attribute = method.GetAttributes().First(static attribute =>
                attribute.AttributeClass?.ToDisplayString() == "Turian.DataAssetListenAttribute");
            var name = attribute.ConstructorArguments[0].Value as string;
            var priority = attribute.ConstructorArguments.Length > 1 ? attribute.ConstructorArguments[1].Value : 0;
            var member = type.GetMembers(name ?? string.Empty).FirstOrDefault();
            var memberType = member switch
            {
                IPropertySymbol property when !property.IsStatic => property.Type as INamedTypeSymbol,
                IFieldSymbol field when !field.IsStatic => field.Type as INamedTypeSymbol,
                _ => null
            };
            var plain = Inherits(memberType, "Turian.Engine.Core.DataAssetEvent");
            var payload = EventPayload(memberType);
            if (method.IsStatic || !method.ReturnsVoid || method.IsGenericMethod ||
                method.Parameters.Any(static parameter => parameter.RefKind != RefKind.None) ||
                !(plain && method.Parameters.Length == 0 || payload is not null && method.Parameters.Length == 1 &&
                    SymbolEqualityComparer.Default.Equals(payload, method.Parameters[0].Type)))
            {
                Error($"{method.Name} must be a void handler matching event member '{name}'.");
                continue;
            }
            subscriptions.Add($"this.@{name} is {{ IsRuntime: true }} channel{subscriptions.Count} "
                              + $"? channel{subscriptions.Count}.Subscribe(this.@{method.Name}, {priority}, this.Id) : null");
        }

        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) { code.AppendLine($"namespace {type.ContainingNamespace};"); }
        code.AppendLine($"partial class {type.Name} : global::Turian.Engine.Core.IDataAssetWiring\n{{");
        for (var i = 0; i < subscriptions.Count; i++)
        {
            code.AppendLine($"    private global::System.IDisposable? __dataAssetSubscription{i};");
        }
        code.AppendLine("    void global::Turian.Engine.Core.IDataAssetWiring.SubscribeDataAssetEvents()\n    {");
        code.AppendLine("        var wiring = (global::Turian.Engine.Core.IDataAssetWiring)this;");
        code.AppendLine("        wiring.DisposeDataAssetEvents();\n        try\n        {");
        for (var i = 0; i < subscriptions.Count; i++)
        {
            code.AppendLine($"            __dataAssetSubscription{i} = {subscriptions[i]};");
        }
        code.AppendLine("        }\n        catch { wiring.DisposeDataAssetEvents(); throw; }\n    }");
        code.AppendLine("    void global::Turian.Engine.Core.IDataAssetWiring.DisposeDataAssetEvents()\n    {");
        for (var i = 0; i < subscriptions.Count; i++)
        {
            code.AppendLine($"        __dataAssetSubscription{i}?.Dispose();\n        __dataAssetSubscription{i} = null;");
        }
        code.AppendLine("    }\n}");
        output.AddSource($"{type.ToDisplayString()}.DataAssetWiring.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
        return;

        void Error(string message) => output.ReportDiagnostic(Diagnostic.Create(InvalidWire,
            methods[0].Locations.FirstOrDefault(), message));
    }

    static ITypeSymbol? EventPayload(INamedTypeSymbol? type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() == "Turian.Engine.Core.DataAssetEvent<T>")
            {
                return current.TypeArguments[0];
            }
        }
        return null;
    }

    static bool Inherits(INamedTypeSymbol? type, string name)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == name) { return true; }
        }
        return false;
    }
}
