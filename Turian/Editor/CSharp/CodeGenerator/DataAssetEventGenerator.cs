namespace Turian.CSharp.CodeGenerator;

/// <summary>Generates closed typed event definitions and registers their serialization without runtime construction.</summary>
[Generator]
public sealed class DataAssetEventGenerator : IIncrementalGenerator
{
    static readonly DiagnosticDescriptor InvalidDefinition = new("TURDDD002", "Invalid DataAsset event definition",
        "Event definitions require a top-level non-generic record, a valid class name and a nonempty type GUID",
        "DataAssetDrivenDesign", DiagnosticSeverity.Error, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var records = context.SyntaxProvider.ForAttributeWithMetadataName("Turian.DataAssetEventDefinitionAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => ((INamedTypeSymbol)syntax.TargetSymbol, syntax.Attributes[0]));
        context.RegisterSourceOutput(records, static (output, model) =>
        {
            var (type, attribute) = model;
            var name = attribute.ConstructorArguments[0].Value as string ?? string.Empty;
            var guid = attribute.ConstructorArguments[1].Value as string;
            if (!type.IsRecord || type.IsGenericType || type.ContainingType is not null ||
                !SyntaxFacts.IsValidIdentifier(name) || !System.Guid.TryParse(guid, out var id) || id == System.Guid.Empty)
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidDefinition, type.Locations.FirstOrDefault()));
                return;
            }
            const string core = "global::Turian.Engine.Core";
            var payload = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var visibility = type.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
            var ns = type.ContainingNamespace.IsGlobalNamespace ? string.Empty : $"namespace {type.ContainingNamespace};";
            var source = $$"""
                // <auto-generated/>
                #nullable enable
                {{ns}}
                /// <summary>A typed gameplay event asset for {{type.Name}} payloads.</summary>
                [global::MASS4.Attributes.TypeId("{{id:D}}")]
                [global::Turian.CreateAssetMenu("DataAsset/DataAssetEvent/{{name}}", "{{name}}")]
                {{visibility}} sealed class {{name}} : {{core}}.DataAssetEvent<{{payload}}>
                {
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void RegisterDefinition()
                    {
                        {{core}}.TypeRegistry.Register(new global::System.Guid("{{id:D}}"), typeof({{name}}));
                        {{core}}.GeneratedSerializers.Register(typeof({{name}}), new {{core}}.GeneratedSerializer(
                            static () => new {{name}}(),
                            static (writer, value, options) =>
                            {
                                writer.WriteString("Id", value.Id);
                                writer.WriteNumber("SchemaVersion", (({{name}})value).SchemaVersion);
                            },
                            static (value, property, options) =>
                            {
                                if (property.Name == "Id") { value.Id = property.Value.GetGuid(); return true; }
                                if (property.Name == "SchemaVersion")
                                {
                                    (({{name}})value).SchemaVersion = property.Value.GetInt32(); return true;
                                }
                                return false;
                            },
                            static (value, member, memberValue) => false,
                            static member => null));
                    }
                }
                """;
            output.AddSource($"{type.ToDisplayString()}.DataAssetEvent.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}
